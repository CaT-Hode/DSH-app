import assert from 'node:assert/strict'
import test from 'node:test'
import { JSDOM } from 'jsdom'
import { readFileSync } from 'node:fs'
import createSidebarMotionClient from '../client/sidebar-motion.mjs'

function fixture(t) {
  const dom = new JSDOM('<!doctype html><html data-dsh-app-ui><head></head><body><div id="root"><div data-dsh-app-frame style="grid-template-columns: 280px minmax(400px, 1fr) minmax(0px, 600px); --dsh-app-overlay-tracks: previous; --dsh-app-chat-inset: 17px"><div data-dsh-center-col><header data-window-drag></header><div data-conversation-scroll><div data-chat-flow></div></div><div data-composer-seat></div></div><div data-shell-overlay><div data-sidebar-right-session="session"><div data-sidebar-right-panel="push" data-sidebar-right-open><div class="P3OORG_panelBody"><div><div data-dockkit-host="dock"><section data-dockkit-content="guide" data-dockkit-pane="pane"><div data-dockkit-strip></div><div><div class="P3OORG_tabBody"><section data-dsh-app-summary><input value="unsaved text"></section></div></div></section></div><div data-dockkit-host="float"><section data-dockkit-float="floating"></section></div></div></div></div></div></div></div></div></body></html>', { pretendToBeVisual: true })
  const original = Object.getOwnPropertyDescriptor(globalThis, 'document')
  Object.defineProperty(globalThis, 'document', { value: dom.window.document, configurable: true })
  const { document, window } = dom.window
  const frame = document.querySelector('[data-dsh-app-frame]')
  const panel = document.querySelector('[data-sidebar-right-panel]')
  let summaryWidth = 350, viewerWidth = 715
  panel.getBoundingClientRect = () => ({ width: panel.hasAttribute('data-dsh-app-panel-summary') ? summaryWidth : viewerWidth })
  const frames = new Map()
  let next = 0
  window.requestAnimationFrame = callback => { const id = ++next; frames.set(id, callback); return id }
  window.cancelAnimationFrame = id => frames.delete(id)
  const tick = async () => {
    await Promise.resolve()
    const pending = [...frames.values()]; frames.clear()
    for (const callback of pending) callback(0)
    await Promise.resolve()
  }
  let dispose
  createSidebarMotionClient().install({ effect: callback => { dispose = callback() } })
  t.after(() => { dispose?.(); dom.window.close(); if (original) Object.defineProperty(globalThis, 'document', original); else delete globalThis.document })
  return { document, window, frame, panel, tick, frames, resizePanel: (summary, viewer) => { summaryWidth = summary; viewerWidth = viewer }, dispose: () => { dispose?.(); dispose = undefined } }
}

test('resting summary keeps the full canvas and reserves only content inset through close', async t => {
  const f = fixture(t)
  const input = f.panel.querySelector('input')
  const nativeTracks = f.frame.style.gridTemplateColumns
  assert.ok(f.panel.hasAttribute('data-dsh-app-panel-summary'))
  assert.ok(f.frame.hasAttribute('data-dsh-app-right-summary'))
  assert.ok(f.frame.hasAttribute('data-dsh-app-right-overlay'))
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-overlay-tracks'), '280px minmax(0px, 1fr) minmax(0px, 0px)')
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-chat-inset'), '382px')
  assert.equal(f.frame.style.gridTemplateColumns, nativeTracks, 'native remains the writer of layout source geometry')
  f.panel.removeAttribute('data-sidebar-right-open')
  await f.tick()
  assert.equal(f.frame.hasAttribute('data-dsh-app-right-summary'), false)
  assert.ok(f.frame.hasAttribute('data-dsh-app-right-overlay'), 'closing does not briefly reinstate the native separate canvas track')
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-chat-inset'), '0px')
  assert.ok(f.panel.hasAttribute('data-dsh-app-panel-summary'), 'closed summary retains its intrinsic card geometry for the exit')
  assert.equal(f.panel.querySelector('input'), input)
  assert.equal(input.value, 'unsaved text')
  assert.ok(f.document.querySelector('[data-dockkit-float]'), 'floats remain mounted under native ownership')
  f.dispose()
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-overlay-tracks'), 'previous')
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-chat-inset'), '17px')
  assert.equal(f.frame.hasAttribute('data-dsh-app-right-overlay'), false)
  assert.equal(f.panel.hasAttribute('data-dsh-app-panel-summary'), false)
  assert.equal(f.frame.hasAttribute('data-dsh-app-right-mode-changing'), false)
  assert.equal(f.frames.size, 0)
})

test('viewers and split panes reserve content inset on the shared canvas, while fullscreen needs no inset', async t => {
  const f = fixture(t)
  const host = f.panel.querySelector('[data-dockkit-host="dock"]')
  const summary = host.querySelector('[data-dsh-app-summary]')
  const viewer = host.cloneNode(true)
  viewer.querySelector('[data-dsh-app-summary]').removeAttribute('data-dsh-app-summary')
  viewer.querySelector('[data-dockkit-content]').setAttribute('data-dockkit-content', 'file')
  host.after(viewer)
  await f.tick()
  assert.equal(f.frame.hasAttribute('data-dsh-app-right-summary'), false)
  assert.equal(f.panel.hasAttribute('data-dsh-app-panel-summary'), false)
  assert.ok(f.frame.hasAttribute('data-dsh-app-right-overlay'))
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-overlay-tracks'), '280px minmax(0px, 1fr) minmax(0px, 0px)')
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-chat-inset'), '747px')
  assert.ok(f.frame.hasAttribute('data-dsh-app-right-mode-changing'), 'mode changes animate even when native expanded state does not change')
  viewer.hidden = true
  await f.tick()
  assert.ok(f.frame.hasAttribute('data-dsh-app-right-summary'))
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-chat-inset'), '382px')
  f.panel.parentElement.style.cssText = 'position: relative; width: 0px'
  f.panel.style.cssText = 'width: 100vw; --dsh-sidebar-width: 100vw'
  f.panel.setAttribute('data-sidebar-right-panel', 'fullscreen')
  await f.tick()
  assert.equal(f.frame.hasAttribute('data-dsh-app-right-summary'), false)
  assert.ok(f.frame.hasAttribute('data-dsh-app-right-overlay'))
  assert.equal(f.frame.style.getPropertyValue('--dsh-app-chat-inset'), '0px')
  assert.equal(f.panel.querySelector('[data-dsh-app-summary]'), summary)
  assert.equal(f.panel.hasAttribute('aria-hidden'), false, 'native focus and accessibility state stay owned by the native panel')
})

